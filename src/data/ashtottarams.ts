// Ashtottara Shatanamavalis (108 names) supplied by the app owner from their family's pooja text.
// Used in the Archana step: offer a flower, bilva leaf or akshatas at each name.
// Ganesha, Venkateswara and Ayyappa lists: obvious font-conversion slips and one-letter typos were corrected
// (e.g. "ద్త్వెమాతురాయ" → "ద్వైమాతురాయ"); every change is listed in CORRECTIONS below.

export interface NameEntry {
  name: string;
  /** Alternative reading given in the family text, e.g. "దీపాయై నమః". */
  alt?: string;
}

export interface Namavali {
  id: string;
  title: { en: string; te: string };
  names: NameEntry[];
  closing?: string;
}

/** One name per line ("ఓం … నమః", optionally ending in "।"); "(10)" counters are dropped and "[…]" becomes the alternative reading. */
const parse = (text: string): NameEntry[] => text.split('\n').map((l) => l.replace(/\(\d+\)/, '').replace(/\s*।\s*$/, '').trim()).flatMap((l) => {
  const alt = l.match(/\[([^\]]+)\]/)?.[1].trim();
  const name = l.replace(/\s*\[[^\]]+\]\s*/, ' ').replace(/\s+/g, ' ').trim();
  return /^ఓం .+ నమః$/.test(name) ? [{ name, alt }] : [];
});

