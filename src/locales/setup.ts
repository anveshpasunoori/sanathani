/** The short explanation under each tradition's name. */
export function traditionNote(id: TraditionId, lang: Lang): string {
  const n = NOTES[lang];
  if (id === 'north') return n.north;
  if (id === 'ta') return n.tamil;
  if (id === 'ml') return n.kerala;
  if (id === 'gu') return n.gujarat;
  if (id === 'bn') return n.bengal;
  if (id === 'or') return n.odisha;
  return id === 'te' ? `${n.amanta} ${n.telangana}` : n.amanta;
}
